/** Fills {name} placeholders. */
export const fill = (s, params = {}) => String(s).replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));

/** A counted noun ("3 cards", "٣ كروت") from a plural form object. */
export function plural(forms, n) {
  if ('other' in forms) return fill(n === 1 ? forms.one : forms.other, { n });
  const f = n === 1 ? forms.one : n === 2 ? forms.two : n >= 3 && n <= 10 ? forms.few : forms.many;
  return fill(f, { n });
}
